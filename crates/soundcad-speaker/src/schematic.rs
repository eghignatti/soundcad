//! Crossover schematic as the user draws it : parts on a grid, connected where their
//! terminals meet (wires join their two ends). Converted to the solver's `Project` for evaluation.
//!
//! Grid units; y grows downwards. Two-terminal parts go from terminal `a` to terminal `b`
//! (`a` = + for the generator and drivers); a ground has only `a`.

use crate::network::{Element, Stage, Way};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use soundcad_xover::{Part, PartKind, Project};

#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum Kind {
    Generator,
    Ground,
    Wire,
    Resistor,
    Capacitor,
    Inductor,
    Driver,
}

#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Comp {
    pub kind: Kind,
    pub a: (i32, i32),
    pub b: (i32, i32),
    /// R Ω, C µF, L mH
    pub value: f64,
    /// ESR (C) or DCR (L), Ω
    pub loss: f64,
    /// Driver: unit name
    pub driver: String,
    pub inverted: bool,
    /// Branch generated by the quick filter for this driver (replaced when the filter is applied again).
    pub group: Option<String>,
    /// Value is adjusted by the optimizer.
    #[serde(default)]
    pub opt: bool,
    /// Optimizer limits (0 = automatic: value/10 … value×10).
    #[serde(default)]
    pub opt_min: f64,
    #[serde(default)]
    pub opt_max: f64,
}

impl Comp {
    pub fn new(kind: Kind, a: (i32, i32), b: (i32, i32), value: f64) -> Self {
        Comp { kind, a, b, value, loss: 0.0, driver: String::new(), inverted: false, group: None, opt: false, opt_min: 0.0, opt_max: 0.0 }
    }

    /// R, C or L: a part with a value (wheel stepping, optimizer).
    pub fn has_value(&self) -> bool {
        matches!(self.kind, Kind::Resistor | Kind::Capacitor | Kind::Inductor)
    }

    /// Turns the part by 90° around terminal `a`.
    pub fn rotate(&mut self) {
        let (dx, dy) = (self.b.0 - self.a.0, self.b.1 - self.a.1);
        self.b = (self.a.0 - dy, self.a.1 + dx);
    }
}

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Schematic {
    pub parts: Vec<Comp>,
}

/// Grid length of a two-terminal part and of a driver.
pub const PART_LEN: i32 = 3;
pub const DRIVER_LEN: i32 = 4;
/// Vertical space of one way in the automatic layout.
const BAND: i32 = 9;

impl Schematic {
    /// Solver project: generator 2.83 V behind 1 mΩ; part ids R1, C1, L1, D1 … in drawing order.
    pub fn to_project(&self) -> Project {
        let mut count: HashMap<&str, usize> = HashMap::new();
        let parts = self
            .parts
            .iter()
            .map(|c| {
                let (kind, prefix, params): (PartKind, &str, Vec<(&str, f64)>) = match c.kind {
                    Kind::Generator => (PartKind::Generator, "G", vec![("Eg", 2.83), ("Rg", 0.001)]),
                    Kind::Ground => (PartKind::Ground, "GND", vec![]),
                    Kind::Wire => (PartKind::Wire, "W", vec![]),
                    Kind::Resistor => (PartKind::Resistor, "R", vec![("R", c.value)]),
                    Kind::Capacitor => (PartKind::Capacitor, "C", vec![("C", c.value), ("ESR", c.loss)]),
                    Kind::Inductor => (PartKind::Inductor, "L", vec![("L", c.value), ("DCR", c.loss)]),
                    Kind::Driver => (PartKind::Driver, "D", vec![]),
                };
                let n = count.entry(prefix).or_insert(0);
                *n += 1;
                Part {
                    kind,
                    type_name: format!("{kind:?}"),
                    id: format!("{prefix}{n}"),
                    model: c.driver.clone(),
                    params: params.into_iter().map(|(k, v)| (k.to_string(), v)).collect(),
                    points: if c.kind == Kind::Ground { vec![c.a] } else { vec![c.a, c.b] },
                    open: false,
                    shorted: false,
                    inverted: c.inverted,
                    muted: false,
                }
            })
            .collect();
        Project { drivers: vec![], parts, room: Default::default() }
    }

    /// Generator and supply rail, laid out at the top left.
    fn add_generator(&mut self) {
        let tag = |mut c: Comp| {
            c.group = Some(String::new());
            c
        };
        self.parts.push(tag(Comp::new(Kind::Generator, (0, 0), (0, 4), 2.83)));
        self.parts.push(tag(Comp::new(Kind::Ground, (0, 4), (0, 4), 0.0)));
        self.parts.push(tag(Comp::new(Kind::Wire, (0, 0), (2, 0), 0.0)));
    }

    /// Ladder of one way drawn from the rail at row `row`: series parts along the row, shunt branches
    /// and the driver going down to ground. All parts tagged with the driver name.
    fn add_branch(&mut self, way: &Way, row: i32) {
        let g = Some(way.driver.clone());
        let mut push = |mut c: Comp| {
            c.group = g.clone();
            self.parts.push(c);
        };
        if row > 0 {
            push(Comp::new(Kind::Wire, (2, 0), (2, row), 0.0));
        }
        let elem = |e: &Element, a, b| match *e {
            Element::R(r) => Comp::new(Kind::Resistor, a, b, r),
            Element::C(c) => Comp::new(Kind::Capacitor, a, b, c),
            Element::L(l, dcr) => Comp { loss: dcr, ..Comp::new(Kind::Inductor, a, b, l) },
        };
        let mut x = 2;
        for st in &way.stages {
            match st {
                Stage::Series(e) => {
                    push(elem(e, (x, row), (x + PART_LEN, row)));
                    x += PART_LEN;
                }
                Stage::Shunt(chain) => {
                    push(Comp::new(Kind::Wire, (x, row), (x + 3, row), 0.0));
                    x += 3;
                    let mut y = row;
                    for e in chain {
                        push(elem(e, (x, y), (x, y + PART_LEN)));
                        y += PART_LEN;
                    }
                    push(Comp::new(Kind::Ground, (x, y), (x, y), 0.0));
                }
            }
        }
        // room for the labels of a shunt part before the driver
        push(Comp::new(Kind::Wire, (x, row), (x + 3, row), 0.0));
        x += 3;
        push(Comp { driver: way.driver.clone(), inverted: way.inverted, ..Comp::new(Kind::Driver, (x, row), (x, row + DRIVER_LEN), 0.0) });
        push(Comp::new(Kind::Ground, (x, row + DRIVER_LEN), (x, row + DRIVER_LEN), 0.0));
    }

    /// Automatic layout of ladder ways (one band per way under a common rail).
    pub fn from_ways(ways: &[Way]) -> Schematic {
        let mut s = Schematic::default();
        s.add_generator();
        for (k, w) in ways.iter().enumerate() {
            s.add_branch(w, k as i32 * BAND);
        }
        s
    }

    /// Replaces the branch generated for `way.driver` (or adds a new band below everything), keeping
    /// the rest of the drawing. Untagged parts the user drew for that driver are left alone.
    pub fn replace_branch(&mut self, way: &Way) {
        if !self.parts.iter().any(|c| c.kind == Kind::Generator) {
            self.add_generator();
        }
        let mine = |c: &Comp| c.group.as_deref() == Some(way.driver.as_str());
        // the band row is the lowest horizontal part of the old branch
        let row = self.parts.iter().filter(|c| mine(c) && c.a.1 == c.b.1 && c.kind != Kind::Ground).map(|c| c.a.1).min();
        let had_driver = self.parts.iter().any(|c| c.kind == Kind::Driver && c.driver == way.driver && !mine(c));
        self.parts.retain(|c| !mine(c));
        let row = row.unwrap_or_else(|| {
            let bottom = self.parts.iter().map(|c| c.a.1.max(c.b.1)).max().unwrap_or(0);
            (bottom / BAND + 1) * BAND
        });
        self.add_branch(way, row);
        // the user had placed this driver by hand: keep theirs, drop the generated one
        if had_driver {
            let i = self.parts.iter().rposition(|c| c.kind == Kind::Driver && mine(c)).unwrap();
            self.parts.remove(i);
        }
    }

    /// Renames a driver everywhere (part links and branch tags).
    pub fn rename_driver(&mut self, old: &str, new: &str) {
        for c in &mut self.parts {
            if c.driver == old {
                c.driver = new.to_string();
            }
            if c.group.as_deref() == Some(old) {
                c.group = Some(new.to_string());
            }
        }
    }

    /// Removes a driver and the branch generated for it.
    pub fn remove_driver(&mut self, name: &str) {
        self.parts.retain(|c| c.driver != name && c.group.as_deref() != Some(name));
    }
}

/// Value snapping of the component editor (5 %, E12, E24, E48).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub enum Snap {
    Percent5,
    E12,
    E24,
    E48,
}

const E12: [f64; 12] = [1.0, 1.2, 1.5, 1.8, 2.2, 2.7, 3.3, 3.9, 4.7, 5.6, 6.8, 8.2];
const E24: [f64; 24] = [1.0, 1.1, 1.2, 1.3, 1.5, 1.6, 1.8, 2.0, 2.2, 2.4, 2.7, 3.0, 3.3, 3.6, 3.9, 4.3, 4.7, 5.1, 5.6, 6.2, 6.8, 7.5, 8.2, 9.1];
const E48: [f64; 48] = [
    1.00, 1.05, 1.10, 1.15, 1.21, 1.27, 1.33, 1.40, 1.47, 1.54, 1.62, 1.69, 1.78, 1.87, 1.96, 2.05, 2.15, 2.26, 2.37, 2.49, 2.61, 2.74, 2.87, 3.01,
    3.16, 3.32, 3.48, 3.65, 3.83, 4.02, 4.22, 4.42, 4.64, 4.87, 5.11, 5.36, 5.62, 5.90, 6.19, 6.49, 6.81, 7.15, 7.50, 7.87, 8.25, 8.66, 9.09, 9.53,
];

/// Next (`up`) or previous value of the snap series from `v` (> 0).
pub fn step(v: f64, up: bool, snap: Snap) -> f64 {
    let series: &[f64] = match snap {
        Snap::Percent5 => return if up { v * 1.05 } else { v / 1.05 },
        Snap::E12 => &E12,
        Snap::E24 => &E24,
        Snap::E48 => &E48,
    };
    let d = v.log10().floor();
    let scale = 10f64.powf(d);
    let m = v / scale;
    let tol = 1e-6;
    if up {
        match series.iter().find(|&&s| s > m * (1.0 + tol)) {
            Some(s) => s * scale,
            None => series[0] * scale * 10.0,
        }
    } else {
        match series.iter().rev().find(|&&s| s < m * (1.0 - tol)) {
            Some(s) => s * scale,
            None => series[series.len() - 1] * scale / 10.0,
        }
    }
}

/// `step` for a value where 0 means "none" (losses, optimizer limits): from 0 up goes to `start`, and going
/// down past a tenth of `start` comes back to 0.
pub fn step_from_zero(v: f64, up: bool, start: f64, snap: Snap) -> f64 {
    if v <= 0.0 {
        return if up { start } else { 0.0 };
    }
    let next = step(v, up, snap);
    if !up && next < start * 0.1 { 0.0 } else { next }
}
